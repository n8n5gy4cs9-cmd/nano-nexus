import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Radio, RefreshCw } from "lucide-react";
import { useState } from "react";
import { useNavigate } from "react-router-dom";

import { Button, Popover, PopoverContent, PopoverTrigger, Switch } from "@/components/ui";
import { SHARE_KEY, useShareStatus } from "@/hooks/useShare";
import { api } from "@/lib/api";
import { cn } from "@/lib/cn";
import { toIpcException } from "@/lib/ipc";

/** Title-bar pill: grey when sharing is off, green with the device count when on. */
export function SharePill() {
  const status = useShareStatus();
  const qc = useQueryClient();
  const navigate = useNavigate();
  const [open, setOpen] = useState(false);
  const running = status?.running ?? false;

  const toggle = useMutation({
    mutationFn: (on: boolean) => api.share.setEnabled(on),
    onSuccess: (s) => qc.setQueryData(SHARE_KEY, s),
    onError: () => void qc.invalidateQueries({ queryKey: SHARE_KEY }),
  });
  const pairing = useQuery({
    queryKey: ["share-pairing", running],
    queryFn: api.share.pairingCode,
    enabled: open && running,
    retry: false,
    staleTime: 4 * 60_000,
  });
  const error = toggle.isError ? toIpcException(toggle.error) : null;

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <button
          type="button"
          aria-label={running ? `LAN Share on, ${status?.devices ?? 0} devices` : "LAN Share off"}
          className={cn(
            "flex h-7 items-center gap-1.5 rounded-full border border-border bg-surface-2 px-2.5 text-small hover:bg-surface-3",
            running ? "text-success" : "text-muted",
          )}
        >
          <Radio className="size-3.5" />
          <span className="font-medium">{running ? `Share ${status?.devices ?? 0}` : "Share"}</span>
        </button>
      </PopoverTrigger>
      <PopoverContent className="w-80">
        <div className="flex items-center justify-between">
          <div className="text-body font-semibold">LAN Share</div>
          <Switch
            aria-label="Share on this network"
            checked={running}
            disabled={toggle.isPending}
            onCheckedChange={(on) => toggle.mutate(on)}
          />
        </div>
        {!running ? (
          <p className="mt-2 text-small text-muted">
            Anyone on this Wi-Fi who pairs can chat with your assistants. Files stay on this computer.
          </p>
        ) : (
          <>
            <div className="mt-2 text-small text-muted">Open on your phone:</div>
            <ul className="mt-1 space-y-0.5 text-small">
              {status?.urls.map((u) => (
                <li key={u} className="truncate font-mono">
                  {u}
                </li>
              ))}
            </ul>
            {pairing.data ? (
              <div className="mt-3 flex items-center gap-3">
                <div
                  aria-label="Pairing QR code"
                  className="size-28 shrink-0 overflow-hidden rounded-chip bg-white [&>svg]:size-full"
                  // The SVG is generated by the app's own backend (qrcode crate), never from user input.
                  dangerouslySetInnerHTML={{ __html: pairing.data.qr_svg }}
                />
                <div className="text-small">
                  <div className="text-muted">Scan to pair, or enter the PIN</div>
                  <div className="tnum mt-1 text-lead font-semibold tracking-widest">{pairing.data.code.pin}</div>
                  <Button size="sm" variant="ghost" className="mt-1 -ml-2" onClick={() => void pairing.refetch()}>
                    <RefreshCw />
                    New code
                  </Button>
                </div>
              </div>
            ) : null}
          </>
        )}
        {error ? (
          <p role="alert" className="mt-2 text-small text-danger">
            {error.message}
            {status?.suggested_port ? (
              <Button
                size="sm"
                variant="secondary"
                className="ml-2"
                onClick={() =>
                  void api.share
                    .setSetting("share.port", status.suggested_port ?? 9889)
                    .then(() => toggle.mutate(true))
                }
              >
                Use {status.suggested_port}
              </Button>
            ) : null}
          </p>
        ) : null}
        <div className="mt-3 flex items-center justify-between text-small">
          <span className="text-muted">Paired devices: {status?.devices ?? 0}</span>
          <Button
            size="sm"
            variant="ghost"
            onClick={() => {
              setOpen(false);
              void navigate("/settings/sharing");
            }}
          >
            Sharing settings…
          </Button>
        </div>
      </PopoverContent>
    </Popover>
  );
}
