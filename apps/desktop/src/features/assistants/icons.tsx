export const ASSISTANT_COLORS = ["violet", "teal", "amber", "blue", "green", "red", "indigo", "pink", "slate"] as const;
export type AssistantColor = (typeof ASSISTANT_COLORS)[number];

export const CATEGORIES = ["General", "Documents", "Files", "Code", "Data", "Writing", "System", "Meta", "Custom"] as const;

export function isColor(c: string): c is AssistantColor {
  return (ASSISTANT_COLORS as readonly string[]).includes(c);
}

export function iconFor(name: string): LucideIcon {
  return ASSISTANT_ICONS[name] ?? Sparkles;
}
